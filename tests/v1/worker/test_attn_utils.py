def test_reshape_padded_quantized_kv_cache_preserves_scale_stride():
    num_blocks = 3
    spec = FullAttentionSpec(
        block_size=16,
        num_kv_heads=1,
        head_size=4,
        dtype=torch.int8,
        kv_quant_mode=KVQuantMode.INT8_PER_TOKEN_HEAD,
        page_size_padded=384,
    )
    assert spec.real_page_size_bytes == 128
    assert spec.page_size_bytes == 384

    raw_tensors = {
        "layer": torch.zeros(spec.page_size_bytes * num_blocks, dtype=torch.int8)
    }
    attn_groups = [
        AttentionGroup(
            backend=FakePerTokenScaleBackend,
            layer_names=["layer"],
            kv_cache_spec=spec,
            kv_cache_group_id=0,
        )
    ]

    kv_cache = _reshape_kv_cache(
        attn_groups,
        raw_tensors,
        "int8_per_token_head",
        [spec.block_size],
        {},
    )["layer"]

    assert kv_cache.shape == (num_blocks, 2, 16, 1, 8)
    assert kv_cache.stride(0) == spec.page_size_bytes
    assert kv_cache.stride(1) == 16 * 1 * 8
    assert kv_cache[1, 1].storage_offset() == spec.page_size_bytes + 16 * 1 * 8


def test_modular_runner_delegates_raw_kv_backing_allocation(monkeypatch):
    logical = KVCacheTensor(size=8, shared_by=["layer"])
    config = SimpleNamespace(
        kv_cache_tensors=[logical],
        kv_cache_groups=[SimpleNamespace(layer_names=["layer"])],
    )
    calls = []

    def allocate(tensors, size, device):
        calls.append((tensors, size, device))
        return torch.empty(size, dtype=torch.int8, device=device)

    monkeypatch.setattr(
        KVConnectorModelRunnerMixin,
        "allocate_kv_cache_backing",
        staticmethod(allocate),
    )

    result = _allocate_kv_cache(config, {}, torch.device("cpu"))

    assert result == {"layer": result["layer"]}
    assert calls == [([logical], 8, torch.device("cpu"))]
